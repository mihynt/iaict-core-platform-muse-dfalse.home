"""FIELD REGISTRY - the single source of truth for record shape (T-032).

Owner direction (2026-11-04): the platform keeps the schema-first path
used by large engineering organisations - define the data model ONCE,
generate everything else from it, and let machine checks guard the
boundary. This module is that one definition for every production
record kind. From it, tools/gen_fields.py generates:

  - backend/app/records_spec.py     (SPECS + RECORD_REFS + REF_ID_COLUMN)
  - deploy/cloudflare/public/fields.js  (UI labels, detail specs, enums)
  - contracts/iaict.proto           (Protobuf contract - field numbers
                                     are append-only, never reused)
  - contracts/iaict.graphql         (GraphQL SDL contract)

The generated contracts keep the microservices / GraphQL / Protobuf
path open: a future service split consumes the .proto / .graphql
artefacts instead of re-deriving shapes from code. Runtime stays a
modular monolith until a split is justified (Shopify's position:
extraction is a deployment-topology change, not an architecture one).

RULES
- Add or change a field HERE, then run:  python3 tools/gen_fields.py
- Never edit a generated file by hand; the drift test
  (backend/tests/test_fields_codegen.py) fails the suite on mismatch.
- Field numbers in contracts/field_numbers.json are append-only.
- Each field dict: name; col = principal column type in the store
  schemas (text|num|date|ts|json|bool) or absent for payload fields;
  label = Vietnamese UI label; input = form control kind; enum = key
  into ENUMS; ref/ref_id = validated reference + its FK column;
  api = RecordIn annotation when the field is declared on the API
  model; pii = personally identifiable (Bang 6 protection applies).
- NOT record fields (route-consumed, intentionally absent here):
  the zone status-change metadata status_change_reason /
  status_decision_doc / status_remediation.
"""
